"""
workload.py - Generates the request streams (the "input" to both simulators).

KEY IDEA: a workload is just a list of requests, each with
    - arrival_time (seconds from start)
    - exec_time    (how long the request needs to run)
The SAME list is given to the serverless simulator and the VM simulator,
so the comparison is fair. Using a seed makes results reproducible.
"""
from dataclasses import dataclass
import numpy as np
import config as C


@dataclass(frozen=True)
class Request:
    req_id: int
    arrival_time: float   # seconds
    exec_time: float      # seconds


def _make_requests(arrivals, rng, mean_exec):
    """Sort arrival times and attach a random execution time to each."""
    arrivals = np.sort(np.asarray(arrivals, dtype=float))
    # Exponential durations: many short requests, a few long ones.
    # Drawn AFTER arrivals from the same rng -> fully determined by the seed.
    durations = rng.exponential(mean_exec, size=len(arrivals))
    return [Request(i, float(a), float(d))
            for i, (a, d) in enumerate(zip(arrivals, durations))]


def steady(seed=C.DEFAULT_SEED, rate=C.STEADY_RATE, duration=C.SIM_DURATION_S,
           jitter=C.STEADY_JITTER, mean_exec=C.MEAN_EXEC_TIME_S):
    """Workload 1: requests at ~constant intervals (1/rate, +-jitter)."""
    rng = np.random.default_rng(seed)
    n = int(rate * duration)
    gaps = (1.0 / rate) * rng.uniform(1 - jitter, 1 + jitter, size=n)
    arrivals = np.cumsum(gaps)
    arrivals = arrivals[arrivals < duration]
    return _make_requests(arrivals, rng, mean_exec)


def bursty(seed=C.DEFAULT_SEED, base_rate=C.BURSTY_BASE_RATE,
           num_bursts=C.BURSTY_NUM_BURSTS, burst_size=C.BURSTY_BURST_SIZE,
           burst_window=C.BURSTY_BURST_WINDOW_S, duration=C.SIM_DURATION_S,
           mean_exec=C.MEAN_EXEC_TIME_S):
    """Workload 2: low background traffic + short, intense bursts."""
    rng = np.random.default_rng(seed)
    # background traffic: Poisson process (random gaps) at base_rate
    n_base = rng.poisson(base_rate * duration)
    arrivals = list(rng.uniform(0, duration, size=n_base))
    # bursts spread evenly across the run: at 1/(k+1) of the duration
    for k in range(1, num_bursts + 1):
        start = duration * k / (num_bursts + 1)
        arrivals.extend(start + rng.uniform(0, burst_window, size=burst_size))
    return _make_requests(arrivals, rng, mean_exec)


def variable(seed=C.DEFAULT_SEED, mean_rate=C.VARIABLE_MEAN_RATE,
             amplitude=C.VARIABLE_AMPLITUDE, period=C.VARIABLE_PERIOD_S,
             duration=C.SIM_DURATION_S, mean_exec=C.MEAN_EXEC_TIME_S):
    """Workload 3: arrival rate rises and falls like a sine wave.
    rate(t) = mean_rate * (1 + amplitude * sin(2*pi*t/period))
    Generated by 'thinning': draw candidates at the max rate, keep each
    with probability rate(t)/max_rate."""
    rng = np.random.default_rng(seed)
    max_rate = mean_rate * (1 + amplitude)
    n_cand = rng.poisson(max_rate * duration)
    cand = np.sort(rng.uniform(0, duration, size=n_cand))
    rate_t = mean_rate * (1 + amplitude * np.sin(2 * np.pi * cand / period))
    keep = rng.uniform(0, 1, size=n_cand) < (rate_t / max_rate)
    return _make_requests(cand[keep], rng, mean_exec)


def idle_to_burst(seed=C.DEFAULT_SEED, idle=C.IDLE_DURATION_S,
                  burst_rate=C.IDLE_BURST_RATE,
                  burst_duration=C.IDLE_BURST_DURATION_S,
                  warmup=C.WARMUP_DURATION_S, mean_exec=C.MEAN_EXEC_TIME_S):
    """Workload 4: short warm-up -> long silence -> sudden heavy burst.
    The warm-up creates warm serverless instances. If the silence is longer
    than the idle timeout those instances are destroyed, so the burst
    meets a cold platform. The burst starts at absolute time `idle`."""
    rng = np.random.default_rng(seed)
    n_warm = rng.poisson(burst_rate * warmup)
    n_burst = rng.poisson(burst_rate * burst_duration)
    arrivals = np.concatenate([rng.uniform(0, warmup, size=n_warm),
                               idle + rng.uniform(0, burst_duration, size=n_burst)])
    return _make_requests(arrivals, rng, mean_exec)


def horizon_of(name, **kw):
    """Nominal length (seconds) of a workload = the window the VMs are paid for."""
    if name == "idle_to_burst":
        return kw.get("idle", C.IDLE_DURATION_S) + kw.get("burst_duration", C.IDLE_BURST_DURATION_S)
    return kw.get("duration", C.SIM_DURATION_S)


def profile_of(name, **kw):
    """Piecewise-constant arrival-RATE description of a workload, used ONLY by the
    analytical model (analytical.py). Returns (phases, pattern) where
      phases  = list of (t_start, t_end, rate_rps)   (rate 0 = silence)
      pattern = "regular" (near-deterministic gaps) or "poisson" (random gaps)
    It mirrors the generators above, so keep the two in sync if either changes."""
    if name == "steady":
        d = kw.get("duration", C.SIM_DURATION_S)
        return [(0.0, d, kw.get("rate", C.STEADY_RATE))], "regular"
    if name == "bursty":
        d = kw.get("duration", C.SIM_DURATION_S)
        base = kw.get("base_rate", C.BURSTY_BASE_RATE)
        nb = kw.get("num_bursts", C.BURSTY_NUM_BURSTS)
        win = kw.get("burst_window", C.BURSTY_BURST_WINDOW_S)
        brate = kw.get("burst_size", C.BURSTY_BURST_SIZE) / win
        starts = [d * k / (nb + 1) for k in range(1, nb + 1)]
        phases, t = [], 0.0
        for s0 in starts:
            phases += [(t, s0, base), (s0, s0 + win, base + brate)]
            t = s0 + win
        phases.append((t, d, base))
        return [p for p in phases if p[1] > p[0]], "poisson"
    if name == "variable":
        d = kw.get("duration", C.SIM_DURATION_S)
        mean = kw.get("mean_rate", C.VARIABLE_MEAN_RATE)
        amp = kw.get("amplitude", C.VARIABLE_AMPLITUDE)
        per = kw.get("period", C.VARIABLE_PERIOD_S)
        bin_s = kw.get("bin", 10.0)               # sine wave -> 10 s constant-rate bins
        edges = np.arange(0.0, d + 1e-9, bin_s)
        mids = (edges[:-1] + edges[1:]) / 2
        rates = mean * (1 + amp * np.sin(2 * np.pi * mids / per))
        return [(float(a), float(b), float(r)) for a, b, r in zip(edges[:-1], edges[1:], rates)], "poisson"
    if name == "idle_to_burst":
        idle = kw.get("idle", C.IDLE_DURATION_S)
        rate = kw.get("burst_rate", C.IDLE_BURST_RATE)
        bd = kw.get("burst_duration", C.IDLE_BURST_DURATION_S)
        wu = kw.get("warmup", C.WARMUP_DURATION_S)
        return [(0.0, wu, rate), (wu, idle, 0.0), (idle, idle + bd, rate)], "poisson"
    raise ValueError(f"unknown workload {name!r}")


# Lookup used by the experiment runner later
GENERATORS = {
    "steady": steady,
    "bursty": bursty,
    "variable": variable,
    "idle_to_burst": idle_to_burst,
}


if __name__ == "__main__":
    # Quick self-check: run `python workload.py`
    print(f"{'workload':<15}{'requests':>9}{'first(s)':>10}{'last(s)':>10}"
          f"{'avg rate/s':>12}{'mean exec(s)':>14}")
    for name, gen in GENERATORS.items():
        reqs = gen(seed=0)
        a = [r.arrival_time for r in reqs]
        span = horizon_of(name)
        print(f"{name:<15}{len(reqs):>9}{min(a):>10.2f}{max(a):>10.2f}"
              f"{len(reqs)/span:>12.2f}{np.mean([r.exec_time for r in reqs]):>14.3f}")

    # Reproducibility check: same seed -> identical; different seed -> different
    for name, gen in GENERATORS.items():
        same = gen(seed=7) == gen(seed=7)
        diff = gen(seed=7) != gen(seed=8)
        print(f"reproducible[{name}]: same seed identical={same}, different seed differs={diff}")
